"""pell CLI — v0.

Usage:
    pell build <file.pell>            -> emits to stdout
    pell build <file.pell> -o <out>   -> writes to file
    pell build <dir>                  -> compiles every .pell file in the dir
    pell parse <file.pell>            -> prints AST
    pell tokens <file.pell>           -> prints token stream
"""

